#!/usr/bin/env node
/**
 * Sync the user's curated news-image pool from Dropbox into public/news-art/.
 *
 * - Source: ~/Library/CloudStorage/Dropbox/Creation/Entities/Jokuh/News
 * - Output: public/news-art/news-art-<sha1[0..7]>.jpg (1024x1024 center-cropped JPEG)
 * - Manifest: src/data/news-art-manifest.ts (alphabetically stable list)
 *
 * Stable filenames:
 *   We hash the *source* filename so that re-syncing keeps existing
 *   assignments (cardImageForId is stable as long as the pool order is stable).
 *   The manifest is sorted lexicographically so adding/removing one image
 *   changes only the affected slot, never shuffles the rest.
 *
 * Usage:
 *   node scripts/sync-news-art.mjs           # one-off sync
 *   node scripts/sync-news-art.mjs --watch   # keep running, re-sync on changes
 */
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  watch,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const __filename = fileURLToPath(import.meta.url);
const ROOT = resolve(dirname(__filename), "..");

const SOURCE_DIR = join(
  homedir(),
  "Library/CloudStorage/Dropbox/Creation/Entities/Jokuh/News",
);
const OUTPUT_DIR = join(ROOT, "public/news-art");
const MANIFEST_PATH = join(ROOT, "src/data/news-art-manifest.ts");
const SUPPORTED_EXT = new Set([".png", ".jpg", ".jpeg", ".webp"]);
const TARGET_SIZE = 1024;

function shortHash(input) {
  return createHash("sha1").update(input).digest("hex").slice(0, 10);
}

async function transcode(srcPath, destPath) {
  await execFileAsync("ffmpeg", [
    "-loglevel",
    "error",
    "-y",
    "-i",
    srcPath,
    "-vf",
    `scale=${TARGET_SIZE}:${TARGET_SIZE}:force_original_aspect_ratio=increase:flags=lanczos,crop=${TARGET_SIZE}:${TARGET_SIZE}`,
    "-q:v",
    "3",
    "-frames:v",
    "1",
    destPath,
  ]);
}

async function syncOnce() {
  if (!existsSync(SOURCE_DIR)) {
    console.warn(`[sync-news-art] source folder missing: ${SOURCE_DIR}`);
    return;
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });

  const sourceFiles = readdirSync(SOURCE_DIR).filter((name) =>
    SUPPORTED_EXT.has(extname(name).toLowerCase()),
  );
  if (sourceFiles.length === 0) {
    console.warn(`[sync-news-art] no images found in ${SOURCE_DIR}`);
  }

  // Map source filename -> deterministic output name
  const wantedFiles = new Set();
  const manifestEntries = [];

  for (const name of sourceFiles.sort()) {
    const hash = shortHash(name);
    const outName = `news-art-${hash}.jpg`;
    const outPath = join(OUTPUT_DIR, outName);
    wantedFiles.add(outName);
    manifestEntries.push(`/news-art/${outName}`);

    const srcPath = join(SOURCE_DIR, name);
    const srcMtime = statSync(srcPath).mtimeMs;
    const needsRebuild =
      !existsSync(outPath) || statSync(outPath).mtimeMs < srcMtime;
    if (!needsRebuild) continue;

    try {
      await transcode(srcPath, outPath);
      console.log(`[sync-news-art] ${name} -> ${outName}`);
    } catch (err) {
      // ffmpeg missing? fall back to a raw copy.
      console.warn(
        `[sync-news-art] ffmpeg failed for ${name}, copying raw bytes (${err.message})`,
      );
      copyFileSync(srcPath, outPath);
    }
  }

  // Prune images that no longer have a source.
  for (const existing of readdirSync(OUTPUT_DIR)) {
    if (!existing.startsWith("news-art-")) continue;
    if (wantedFiles.has(existing)) continue;
    rmSync(join(OUTPUT_DIR, existing), { force: true });
    console.log(`[sync-news-art] removed orphan ${existing}`);
  }

  manifestEntries.sort();
  const manifest = `// AUTO-GENERATED by scripts/sync-news-art.mjs. Do not edit.
// Run \`npm run sync:news-art\` to regenerate.
export const NEWS_ART_POOL: readonly string[] = ${JSON.stringify(
    manifestEntries,
    null,
    2,
  )};
`;
  writeFileSync(MANIFEST_PATH, manifest, "utf8");
  console.log(
    `[sync-news-art] manifest written (${manifestEntries.length} images)`,
  );
}

async function main() {
  await syncOnce();
  if (process.argv.includes("--watch")) {
    console.log(`[sync-news-art] watching ${SOURCE_DIR}`);
    let pending = false;
    let inflight = false;
    const trigger = () => {
      if (inflight) {
        pending = true;
        return;
      }
      inflight = true;
      syncOnce()
        .catch((err) => console.error("[sync-news-art]", err))
        .finally(() => {
          inflight = false;
          if (pending) {
            pending = false;
            trigger();
          }
        });
    };
    watch(SOURCE_DIR, { persistent: true }, () => {
      // Debounce burst events.
      setTimeout(trigger, 250);
    });
  }
}

main().catch((err) => {
  console.error("[sync-news-art]", err);
  process.exit(1);
});
